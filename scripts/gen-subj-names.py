#!/usr/bin/env python3
"""Records how OpenSSL turns `req -subj` arguments into names, for baldssl
to reproduce.

For each argument of a corpus, with and without `-utf8`, runs
`openssl req -new -subj ...` and writes one line:

    <utf8: 0|1> <argument hex> <ok|error> <Name DER hex, or -> <warnings>

the Name being the subject of the request OpenSSL wrote, and warnings the
number of lines OpenSSL printed about skipped attributes.

Usage: gen-subj-names.py OPENSSL > tests/fixtures/req/subj-names.txt
"""

import subprocess
import sys
import tempfile
from pathlib import Path

CORPUS: list[bytes] = [
    b"/C=BE/O=Org/CN=test.example",
    b"/CN=a+O=b",
    b"/O=b+CN=a",
    b"/CN=a+CN=b/O=c",
    b"/CN=x\\/y",
    b"/CN=a\\+b",
    b"/CN=a\\\\b",
    b"/CN=",
    b"/CN=/O=org",
    b"/XX=foo/CN=a",
    b"/CN=a+XX=b",
    b"/CN=caf\xc3\xa9",
    b"/CN=caf\xe9",
    b"/C=BEL",
    b"/C=B",
    b"/C=B@",
    b"/emailAddress=a@b.example",
    b"/emailAddress=\xc3\xa9@b.example",
    b"/serialNumber=123",
    b"/serialNumber=a@b",
    b"/DC=example/DC=com",
    b"/commonName=long form",
    b"/2.5.4.3=dotted",
    b"/1.2.3.4=unknown dotted",
    b"CN=no slash",
    b"/CN",
    b"/CN=a\\",
    b"/CN=" + b"x" * 64,
    b"/CN=" + b"x" * 65,
    b"/",
    b"/GN=Jane/SN=Doe/initials=J",
    b"/dnQualifier=abc",
    b"/INN=123",
    b"/INN=12a",
    b"/c3=BEL",
    b"/name=x",
    b"/street=1 Main St",
    b"/friendlyName=x",
    b"/CN=sp ace/O=a'b(c)",
    b"/L=Li\xc3\xa8ge/ST=Wallonie",
]


def openssl(
    binary: str, args: list[bytes]
) -> subprocess.CompletedProcess[bytes]:
    # The binary is the one named on the command line.
    return subprocess.run(  # noqa: S603
        [binary.encode(), *args], capture_output=True, check=False
    )


def subject(der: bytes) -> bytes:
    """The subject Name of a DER CertificationRequest: the second field of
    its CertificationRequestInfo."""

    def tlv(data: bytes, i: int) -> tuple[int, int]:
        length = data[i + 1]
        start = i + 2
        if length & 0x80:
            n = length & 0x7F
            length = int.from_bytes(data[start : start + n], "big")
            start += n
        return start, start + length

    request, _ = tlv(der, 0)  # inside CertificationRequest
    info, _ = tlv(der, request)  # inside CertificationRequestInfo
    _, version_end = tlv(der, info)  # past the version
    _, name_end = tlv(der, version_end)
    return der[version_end:name_end]


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    binary = sys.argv[1]
    version = openssl(binary, [b"version"]).stdout.decode().strip()
    print(f"# How {version} reads req -subj.")
    print("# Format: <utf8> <argument hex> <ok|error> <Name hex|-> <warnings>.")
    print("# Generated by scripts/gen-subj-names.py.")
    with tempfile.TemporaryDirectory() as tmp:
        key = Path(tmp) / "key.pem"
        openssl(
            binary,
            [b"genpkey", b"-algorithm", b"ED25519", b"-out", str(key).encode()],
        )
        for utf8 in (0, 1):
            for arg in CORPUS:
                out = Path(tmp) / "req.der"
                out.unlink(missing_ok=True)
                cmd = [b"req", b"-new", b"-key", str(key).encode()]
                cmd += [b"-subj", arg, b"-outform", b"DER"]
                cmd += [b"-out", str(out).encode()]
                if utf8:
                    cmd.append(b"-utf8")
                result = openssl(binary, cmd)
                warnings = sum(
                    1
                    for line in result.stderr.decode(
                        errors="replace"
                    ).splitlines()
                    if " warning: " in line
                )
                if result.returncode == 0 and out.exists():
                    name = subject(out.read_bytes()).hex()
                    print(f"{utf8} {arg.hex()} ok {name} {warnings}")
                else:
                    print(f"{utf8} {arg.hex()} error - {warnings}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
