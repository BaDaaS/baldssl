#!/usr/bin/env python3
"""Records certificates `openssl x509 -req` issues, for baldssl to reproduce.

For one CA per curve (the first fixture key of each curve, with a
self-signed certificate from `openssl req -x509`) and every key of
tests/fixtures/keys/keypairs.txt as the subject of a request, runs

    openssl x509 -req -in <request> -CA <ca> -CAkey <ca key>
        -set_serial 0x0102 [-not_before ... -not_after ...]

with OpenSSL's default configuration, and writes one line:

    <CA curve> <CA private key hex> <CA certificate hex> <request hex>
        <certificate hex>

The private key is the fixture's first column (a scalar, or an Ed25519
seed). OpenSSL 3.0's x509 has no -not_before, so it gets -days 30; the
validity is read back from the certificate.

Usage: gen-issued.py OPENSSL > tests/fixtures/x509-req/issued-<line>.txt
"""

import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def openssl(binary: str, args: list[str]) -> bytes:
    # The binary is the one named on the command line.
    result = subprocess.run(  # noqa: S603
        [binary, *args], capture_output=True, check=False
    )
    if result.returncode != 0:
        sys.exit(result.stderr.decode(errors="replace"))
    return result.stdout


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    binary = sys.argv[1]
    version = openssl(binary, ["version"]).decode().strip()
    validity = (
        ["-days", "30"]
        if version.startswith("OpenSSL 3.0.")
        else ["-not_before", "20261122000000Z", "-not_after", "20510101000000Z"]
    )
    print(f"# Certificates issued by x509 -req, {version}.")
    print(
        "# Format: <CA curve> <CA private key hex> <CA certificate hex>"
        " <request hex> <certificate hex>."
    )
    print("# Generated by scripts/gen-issued.py.")
    keys = [
        line.split()
        for line in (ROOT / "tests/fixtures/keys/keypairs.txt")
        .read_text()
        .splitlines()
        if line.strip() and not line.startswith("#")
    ]
    cas: dict[str, list[str]] = {}
    for fields in keys:
        cas.setdefault(fields[0], fields)
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        for curve, ca_private, _, ca_pkcs8 in cas.values():
            (work / "ca.der").write_bytes(bytes.fromhex(ca_pkcs8))
            openssl(
                binary,
                [
                    "req", "-x509", "-new", "-key", str(work / "ca.der"),
                    "-keyform", "DER", "-subj", "/CN=Example CA",
                    "-days", "3650", "-outform", "DER",
                    "-out", str(work / "ca.crt"),
                ],
            )  # fmt: skip
            ca = (work / "ca.crt").read_bytes()
            (work / "ca.pem").write_bytes(
                openssl(
                    binary,
                    ["x509", "-in", str(work / "ca.crt"), "-inform", "DER"],
                )
            )
            for fields in keys:
                (work / "leaf.der").write_bytes(bytes.fromhex(fields[3]))
                openssl(
                    binary,
                    [
                        "req", "-new", "-key", str(work / "leaf.der"),
                        "-keyform", "DER", "-subj", "/CN=leaf.example",
                        "-outform", "DER", "-out", str(work / "leaf.csr"),
                    ],
                )  # fmt: skip
                openssl(
                    binary,
                    [
                        "x509", "-req", "-in", str(work / "leaf.csr"),
                        "-inform", "DER", "-CA", str(work / "ca.pem"),
                        "-CAkey", str(work / "ca.der"), "-CAkeyform", "DER",
                        "-set_serial", "0x0102", *validity,
                        "-outform", "DER", "-out", str(work / "leaf.crt"),
                    ],
                )  # fmt: skip
                request = (work / "leaf.csr").read_bytes().hex()
                cert = (work / "leaf.crt").read_bytes().hex()
                print(f"{curve} {ca_private} {ca.hex()} {request} {cert}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
