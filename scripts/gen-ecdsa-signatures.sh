#!/usr/bin/env bash
#
# Records ECDSA signatures made by OpenSSL, for baldssl to verify: every EC
# key of tests/fixtures/keys/keypairs.txt signs a few messages with each
# SHA-2 hash (openssl dgst -sign, random nonces). One line per signature:
#
#   <curve> <hash> <message hex> <public key hex> <signature hex>
#
# the empty message written `-`, the public key an uncompressed SEC 1 point, the signature the DER
# ECDSA-Sig-Value.
#
# Usage:
#   scripts/gen-ecdsa-signatures.sh <path/to/openssl> \
#       > tests/fixtures/ecdsa/openssl-signatures.txt
#
set -euo pipefail

if [[ "$#" -ne 1 ]]; then
    echo "usage: $0 <openssl>" >&2
    exit 2
fi
OPENSSL=$1
ROOT=$(cd "$(dirname "$0")/.." && pwd)
WORK=$(mktemp -d "${TMPDIR:-/tmp}/baldssl-ecdsa.XXXXXX")
trap 'rm -rf "$WORK"' EXIT

# The messages: empty, short, and longer than every hash block.
printf '' >"$WORK/m0"
printf 'sample' >"$WORK/m1"
head -c 300 /dev/zero | tr '\0' 'a' >"$WORK/m2"

hex() { od -An -v -tx1 "$1" | tr -d ' \n'; }

echo "# ECDSA signatures made by $("$OPENSSL" version), for verification."
echo "# Format: <curve> <hash> <message hex, - if empty> <public key hex>"
echo "# <signature hex>."
echo "# Generated by scripts/gen-ecdsa-signatures.sh."
grep '^P-' "$ROOT/tests/fixtures/keys/keypairs.txt" |
    while read -r curve _private public pkcs8; do
        printf '%s' "$pkcs8" | xxd -r -p >"$WORK/key.der"
        for hash in sha224 sha256 sha384 sha512; do
            for m in m0 m1 m2; do
                "$OPENSSL" dgst "-$hash" -sign "$WORK/key.der" -keyform DER \
                    -out "$WORK/sig" "$WORK/$m"
                name=$(printf '%s' "$hash" | sed 's/sha/SHA-/')
                message=$(hex "$WORK/$m")
                echo "$curve $name ${message:--} $public $(hex "$WORK/sig")"
            done
        done
    done
