#!/usr/bin/env python3
"""Records how OpenSSL prints certificate requests, for baldssl to reproduce.

For every request of tests/fixtures/req/requests.txt, runs
`openssl req -in <request> -inform DER -noout -text` and writes one line:

    <request hex> <text hex>

Run it once per release line baldssl imitates, with an OpenSSL of it:
3.0, 3 and 4.

Usage: gen-request-texts.py OPENSSL > tests/fixtures/req/text-<line>.txt
"""

import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    binary = sys.argv[1]
    # The binary is the one named on the command line.
    version = (
        subprocess.run(  # noqa: S603
            [binary, "version"], capture_output=True, check=True
        )
        .stdout.decode()
        .strip()
    )
    print(f"# Request texts printed by {version}.")
    print("# Format: <request hex> <text hex>.")
    print("# Generated by scripts/gen-request-texts.py.")
    requests = (ROOT / "tests/fixtures/req/requests.txt").read_text()
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "req.der"
        for line in requests.splitlines():
            if not line or line.startswith("#"):
                continue
            request = line.split()[3]
            path.write_bytes(bytes.fromhex(request))
            text = subprocess.run(  # noqa: S603
                [binary, "req", "-in", str(path), "-inform", "DER",
                 "-noout", "-text"],
                capture_output=True, check=True,
            ).stdout  # fmt: skip
            print(f"{request} {text.hex()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
