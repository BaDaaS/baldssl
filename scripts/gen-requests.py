#!/usr/bin/env python3
"""Records certificate requests OpenSSL writes, for baldssl to reproduce.

For every key of tests/fixtures/keys/keypairs.txt and each subject of a
small corpus, runs `openssl req -new -key <key> -subj <subject>` (default
digest, no -utf8) and writes one line:

    <curve> <private key hex> <subject hex> <request DER hex>

The private key is the fixture's first column (a scalar, or an Ed25519
seed).

Usage: gen-requests.py OPENSSL > tests/fixtures/req/requests.txt
"""

import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SUBJECTS: list[bytes] = [
    b"/CN=test.example",
    b"/C=BE/O=Org/CN=x",
    b"/CN=a+O=b/emailAddress=x@y.example",
]


def openssl(
    binary: str, args: list[bytes]
) -> subprocess.CompletedProcess[bytes]:
    # The binary is the one named on the command line.
    return subprocess.run(  # noqa: S603
        [binary.encode(), *args], capture_output=True, check=False
    )


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    binary = sys.argv[1]
    version = openssl(binary, [b"version"]).stdout.decode().strip()
    print(f"# Certificate requests written by {version}.")
    print("# Format: <curve> <private key hex> <subject hex> <request hex>.")
    print("# Generated by scripts/gen-requests.py.")
    keys = (ROOT / "tests/fixtures/keys/keypairs.txt").read_text()
    with tempfile.TemporaryDirectory() as tmp:
        key = Path(tmp) / "key.der"
        out = Path(tmp) / "req.der"
        for line in keys.splitlines():
            fields = line.split()
            if not fields or line.startswith("#"):
                continue
            curve, private, pkcs8 = fields[0], fields[1], fields[3]
            key.write_bytes(bytes.fromhex(pkcs8))
            for subject in SUBJECTS:
                result = openssl(
                    binary,
                    [
                        b"req", b"-new", b"-key", str(key).encode(),
                        b"-keyform", b"DER", b"-subj", subject,
                        b"-outform", b"DER", b"-out", str(out).encode(),
                    ],
                )  # fmt: skip
                if result.returncode != 0:
                    sys.exit(result.stderr.decode(errors="replace"))
                request = out.read_bytes().hex()
                print(f"{curve} {private} {subject.hex()} {request}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
