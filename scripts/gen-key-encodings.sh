#!/usr/bin/env bash
#
# Records how OpenSSL encodes each key of tests/fixtures/keys/keypairs.txt in
# the other formats baldssl reads: SEC 1 (with and without the public key)
# and SubjectPublicKeyInfo (uncompressed and compressed). The keys are the
# ones keypairs.txt already holds, read from its PKCS#8 column, so the two
# files describe the same keys. The tests of baldssl-pkey parse each
# encoding and compare the result with the key.
#
# Usage:
#   scripts/gen-key-encodings.sh <path/to/openssl> \
#       > tests/fixtures/keys/encodings.txt
#

set -euo pipefail

if [[ "$#" -ne 1 ]]; then
    echo "usage: $0 <openssl>" >&2
    exit 2
fi
OPENSSL=$1
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
WORK=$(mktemp -d "${TMPDIR:-/tmp}/baldssl-enc.XXXXXX")
trap 'rm -rf "$WORK"' EXIT

hex() {
    od -An -v -tx1 "$1" | tr -d ' \n'
}

# Runs an OpenSSL conversion of the PKCS#8 key into $WORK/out.der and prints
# it in hexadecimal.
convert() {
    "$OPENSSL" "$@" -inform DER -in "$WORK/key.der" -outform DER \
        -out "$WORK/out.der" 2>/dev/null
    hex "$WORK/out.der"
}

echo "# How OpenSSL encodes the keys of keypairs.txt, in hexadecimal DER."
echo "# Format: <curve> <PKCS#8> <SEC 1> <SEC 1 without the public key>"
echo "# <SubjectPublicKeyInfo> <SubjectPublicKeyInfo, compressed point>;"
echo "# '-' where the format does not apply (SEC 1 for Ed25519)."
echo "# Generated by scripts/gen-key-encodings.sh with $("$OPENSSL" version)."
grep -v '^#' "$ROOT/tests/fixtures/keys/keypairs.txt" |
    while read -r curve _private _public pkcs8; do
        echo "$pkcs8" | xxd -r -p >"$WORK/key.der"
        if [[ "$curve" == ED25519 ]]; then
            echo "$curve $pkcs8 - - $(convert pkey -pubout) -"
        else
            echo "$curve $pkcs8 $(convert ec) $(convert ec -no_public)" \
                "$(convert pkey -pubout)" \
                "$(convert ec -pubout -conv_form compressed)"
        fi
    done
