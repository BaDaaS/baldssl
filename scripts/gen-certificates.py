#!/usr/bin/env python3
"""Records self-signed certificates OpenSSL writes, for baldssl to reproduce.

For every key of tests/fixtures/keys/keypairs.txt, each subject of a small
corpus and each (serial, validity) case, runs

    openssl req -x509 -new -key <key> -subj <subject> -set_serial <serial>
        -not_before <time> -not_after <time>

with OpenSSL's default configuration file (so the extensions of its
`v3_ca` section), and writes one line:

    <curve> <private key hex> <subject hex> <serial hex> <not before>
        <not after> <certificate DER hex>

The private key is the fixture's first column (a scalar, or an Ed25519
seed); the times are seconds after the Unix epoch.

Usage: gen-certificates.py OPENSSL > tests/fixtures/req/certificates.txt
"""

import datetime
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SUBJECTS: list[bytes] = [
    b"/CN=test.example",
    b"/C=BE/O=Org/CN=x",
    b"/CN=a+O=b/emailAddress=x@y.example",
]
# Serials: the smallest, one needing a leading zero octet, and the 159-bit
# maximum OpenSSL draws. Validities: UTCTime, and GeneralizedTime from 2050.
CASES: list[tuple[str, int, int]] = [
    ("01", 1_795_305_600, 1_826_841_600),
    ("80", 2_524_607_999, 2_524_608_000),
    ("7f" + "ff" * 19, 0, 253_402_300_799),
]


def asn1_time(seconds: int) -> bytes:
    moment = datetime.datetime.fromtimestamp(seconds, datetime.UTC)
    return moment.strftime("%Y%m%d%H%M%SZ").encode()


def openssl(
    binary: str, args: list[bytes]
) -> subprocess.CompletedProcess[bytes]:
    # The binary is the one named on the command line.
    return subprocess.run(  # noqa: S603
        [binary.encode(), *args], capture_output=True, check=False
    )


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    binary = sys.argv[1]
    version = openssl(binary, [b"version"]).stdout.decode().strip()
    print(f"# Self-signed certificates written by {version}.")
    print(
        "# Format: <curve> <private key hex> <subject hex> <serial hex>"
        " <not before> <not after> <certificate hex>."
    )
    print("# Generated by scripts/gen-certificates.py.")
    keys = (ROOT / "tests/fixtures/keys/keypairs.txt").read_text()
    with tempfile.TemporaryDirectory() as tmp:
        key = Path(tmp) / "key.der"
        out = Path(tmp) / "cert.der"
        for line in keys.splitlines():
            fields = line.split()
            if not fields or line.startswith("#"):
                continue
            curve, private, pkcs8 = fields[0], fields[1], fields[3]
            key.write_bytes(bytes.fromhex(pkcs8))
            for subject in SUBJECTS:
                for serial, before, after in CASES:
                    result = openssl(
                        binary,
                        [
                            b"req", b"-x509", b"-new",
                            b"-key", str(key).encode(), b"-keyform", b"DER",
                            b"-subj", subject,
                            b"-set_serial", b"0x" + serial.encode(),
                            b"-not_before", asn1_time(before),
                            b"-not_after", asn1_time(after),
                            b"-outform", b"DER", b"-out", str(out).encode(),
                        ],
                    )  # fmt: skip
                    if result.returncode != 0:
                        sys.exit(result.stderr.decode(errors="replace"))
                    cert = out.read_bytes().hex()
                    print(
                        f"{curve} {private} {subject.hex()} {serial}"
                        f" {before} {after} {cert}"
                    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
