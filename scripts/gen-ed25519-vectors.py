#!/usr/bin/env python3
"""Records Ed25519 verdicts and signatures made by OpenSSL, for baldssl to
reproduce.

Writes two files into OUTPUT_DIR:

- `edge-cases.txt`: OpenSSL's verdict on each case of the ed25519-speccheck
  suite (Chalkias, Garillot, Nikolaenko, "Taming the many EdDSAs", ePrint
  2020/1244), whose cases.json is given: `<index> <valid|invalid>
  <message hex> <public key hex> <signature hex>`.
- `openssl-signatures.txt`: signatures OpenSSL makes with every Ed25519 key
  of tests/fixtures/keys/keypairs.txt: `<message hex> <public key hex>
  <signature hex>`.

Usage: gen-ed25519-vectors.py OPENSSL CASES_JSON OUTPUT_DIR
"""

import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
# SubjectPublicKeyInfo around a raw Ed25519 key (RFC 8410 section 4).
SPKI_PREFIX = bytes.fromhex("302a300506032b6570032100")
# PKCS#8 around a raw Ed25519 seed (RFC 8410 section 7).
PKCS8_PREFIX = bytes.fromhex("302e020100300506032b657004220420")
# Not the empty message: `pkeyutl -rawin` cannot read an empty input (it
# fails to allocate a zero-length buffer); RFC 8032 TEST 1 covers it.
MESSAGES = [b"sample", b"a" * 300, bytes(range(256))]


def openssl(binary: str, args: list[str]) -> subprocess.CompletedProcess[str]:
    # The binary is the one named on the command line.
    return subprocess.run(  # noqa: S603
        [binary, *args], capture_output=True, text=True, check=False
    )


def verdict(binary: str, work: Path, case: dict[str, str]) -> str:
    (work / "pub.der").write_bytes(SPKI_PREFIX + bytes.fromhex(case["pub_key"]))
    (work / "msg").write_bytes(bytes.fromhex(case["message"]))
    (work / "sig").write_bytes(bytes.fromhex(case["signature"]))
    result = openssl(
        binary,
        [
            "pkeyutl", "-verify", "-rawin", "-pubin", "-keyform", "DER",
            "-inkey", str(work / "pub.der"), "-in", str(work / "msg"),
            "-sigfile", str(work / "sig"),
        ],
    )  # fmt: skip
    if "Signature Verified Successfully" in result.stdout:
        return "valid"
    if "Signature Verification Failure" in result.stdout:
        return "invalid"
    sys.exit(f"openssl gave no verdict: {result.stderr.strip()}")


def sign(binary: str, work: Path, seed: bytes, message: bytes) -> bytes:
    (work / "key.der").write_bytes(PKCS8_PREFIX + seed)
    (work / "msg").write_bytes(message)
    result = openssl(
        binary,
        [
            "pkeyutl", "-sign", "-rawin", "-keyform", "DER",
            "-inkey", str(work / "key.der"), "-in", str(work / "msg"),
            "-out", str(work / "sig"),
        ],
    )  # fmt: skip
    if result.returncode != 0:
        sys.exit(f"openssl could not sign: {result.stderr.strip()}")
    return (work / "sig").read_bytes()


def main() -> int:
    if len(sys.argv) != 4:
        print(__doc__, file=sys.stderr)
        return 2
    binary, cases_path, out = sys.argv[1], Path(sys.argv[2]), Path(sys.argv[3])
    version = openssl(binary, ["version"]).stdout.strip()
    cases = json.loads(cases_path.read_text(encoding="utf-8"))
    out.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        lines = [
            f"# OpenSSL's verdicts ({version}) on ed25519-speccheck's cases.",
            "# Format: <index> <valid|invalid> <message hex> <public key hex>"
            " <signature hex>.",
            "# Generated by scripts/gen-ed25519-vectors.py.",
        ]
        for i, case in enumerate(cases):
            lines.append(
                f"{i} {verdict(binary, work, case)} {case['message']} "
                f"{case['pub_key']} {case['signature']}"
            )
        (out / "edge-cases.txt").write_text("\n".join(lines) + "\n")

        keys = ROOT / "tests/fixtures/keys/keypairs.txt"
        lines = [
            f"# Ed25519 signatures made by {version}.",
            "# Format: <message hex> <public key hex> <signature hex>.",
            "# Generated by scripts/gen-ed25519-vectors.py.",
        ]
        for line in keys.read_text(encoding="utf-8").splitlines():
            fields = line.split()
            if not fields or fields[0] != "ED25519":
                continue
            seed, public = bytes.fromhex(fields[1]), fields[2]
            for message in MESSAGES:
                signature = sign(binary, work, seed, message).hex()
                lines.append(f"{message.hex()} {public} {signature}")
        (out / "openssl-signatures.txt").write_text("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
