#!/usr/bin/env python3
"""Generate the OID -> (short name, long name) table from OpenSSL's obj_mac.h.

The x509 text printer must name objects exactly as OpenSSL does, so the table
is derived from OpenSSL's own header instead of being typed by hand.

Usage: scripts/gen-objects.py <path/to/obj_mac.h> <openssl-version> > out.rs
"""

import re
import sys
from pathlib import Path


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    path, version = sys.argv[1], sys.argv[2]
    sn, ln, obj = {}, {}, {}
    define = re.compile(r"^#\s*define\s+(SN|LN|OBJ)_(\w+)\s+(.*?)\s*$")
    with Path(path).open(encoding="utf-8") as fh:
        for line in fh:
            m = define.match(line)
            if not m:
                continue
            kind, name, value = m.groups()
            if kind == "SN":
                sn[name] = value.strip('"')
            elif kind == "LN":
                ln[name] = value.strip('"')
            else:
                obj[name] = [t.strip() for t in value.split(",")]

    resolved: dict[str, list[int]] = {}

    def resolve(name: str) -> list[int]:
        if name in resolved:
            return resolved[name]
        arcs = []
        for tok in obj[name]:
            if tok.startswith("OBJ_"):
                arcs.extend(resolve(tok[4:]))
            else:
                arcs.append(int(tok.rstrip("L")))
        resolved[name] = arcs
        return arcs

    rows = {}
    for name in obj:
        if name not in sn and name not in ln:
            continue
        dotted = ".".join(str(a) for a in resolve(name))
        short = sn.get(name, ln.get(name))
        long_ = ln.get(name, short)
        rows[dotted] = (short, long_)

    def key(dotted: str) -> list[int]:
        return [int(a) for a in dotted.split(".")]

    out = sys.stdout
    out.write(
        "// @generated by scripts/gen-objects.py from OpenSSL "
        f"{version} obj_mac.h. Do not edit.\n"
    )
    out.write("//! OpenSSL object names, sorted by OID for binary search.\n\n")
    out.write(
        "/// `(dotted OID, short name, long name)`, sorted by OID arcs.\n"
    )
    out.write("pub(crate) static OBJECTS: &[(&str, &str, &str)] = &[\n")
    for dotted in sorted(rows, key=key):
        short, long = rows[dotted]
        out.write(f"    ({dotted!r}, {short!r}, {long!r}),\n".replace("'", '"'))
    out.write("];\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
