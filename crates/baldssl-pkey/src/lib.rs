//! Private keys: generation, and the PKCS#8 encoding OpenSSL writes.
//!
//! Supported: P-256, P-384, P-521 and Ed25519.
//!
//! # PKCS#8
//!
//! PKCS#8 is the eighth of RSA Laboratories' Public-Key Cryptography
//! Standards: the *Private-Key Information Syntax*, republished as version
//! 1.2 in [RFC 5208][rfc5208] and since generalised by [RFC 5958][rfc5958]
//! (*Asymmetric Key Packages*, which obsoletes it). It is the container for
//! a private key of any algorithm:
//!
//! ```text
//! PrivateKeyInfo ::= SEQUENCE {
//!     version              INTEGER,                -- 0
//!     privateKeyAlgorithm  AlgorithmIdentifier,
//!     privateKey           OCTET STRING,
//!     attributes      [0]  IMPLICIT Attributes OPTIONAL }
//! ```
//!
//! The algorithm identifier says how to read the OCTET STRING, so a
//! `PrivateKeyInfo` is a dependent pair: the type of its second component
//! depends on the first. For EC (`id-ecPublicKey`, with the curve as
//! parameter), the OCTET STRING holds an `ECPrivateKey` ([RFC
//! 5915][rfc5915]); for Ed25519 (`id-Ed25519`, no parameters), a
//! `CurvePrivateKey`, the seed as an OCTET STRING ([RFC 8410][rfc8410]).
//! PKCS#8 also defines `EncryptedPrivateKeyInfo`, the same structure
//! encrypted under a password, which baldssl does not write. In PEM the
//! label is `PRIVATE KEY` ([RFC 7468, section 10][rfc7468]).
//!
//! # The encoding OpenSSL writes
//!
//! OpenSSL writes private keys in PKCS#8 unless `-traditional` is given
//! ([`openssl-pkey`, 3.5][pkey35] and [4.1][pkey41]: "Normally a private
//! key is written using standard format: this is PKCS#8 form"). The exact
//! bytes are those of `openssl genpkey`:
//!
//! - EC: `PrivateKeyInfo { 0, { id-ecPublicKey, <curve> }, OCTET STRING
//!   ECPrivateKey }`, where `ECPrivateKey` is `{ 1, OCTET STRING d, [1] BIT
//!   STRING Q }`: $d$ big-endian at the full length of the group order, $Q$
//!   uncompressed, no `[0]` parameters.
//! - Ed25519: `{ 0, { id-Ed25519 }, OCTET STRING { OCTET STRING seed } }`.
//!
//! The tests compare baldssl's encoding byte for byte with the sixteen keys
//! of `tests/fixtures/keys/keypairs.txt`, generated by OpenSSL 3.5.9; OpenSSL
//! 3.5.9 and 4.1.0 re-encode each of them to the same bytes, which
//! `scripts/pkcs8-agreement.sh` checks.
//!
//! # Structure
//!
//! A [`PrivateKey`] is one of the typed key pairs of `baldssl-crypto`
//! (`EcKeyPair` on each curve, `EdDsaKeyPair` for Ed25519), whose public key
//! is derived from the secret, so a key whose two halves disagree cannot be
//! built. Its encoding is the [`Encodable`] implementation, from the syntax
//! descriptions of `asn1`, and [`Pem`] gives the armour.
//!
//! [rfc5208]: https://www.rfc-editor.org/rfc/rfc5208#section-5
//! [rfc5958]: https://www.rfc-editor.org/rfc/rfc5958#section-2
//! [rfc5915]: https://www.rfc-editor.org/rfc/rfc5915#section-3
//! [rfc8410]: https://www.rfc-editor.org/rfc/rfc8410#section-7
//! [rfc7468]: https://www.rfc-editor.org/rfc/rfc7468#section-10
//! [pkey35]: https://docs.openssl.org/3.5/man1/openssl-pkey/
//! [pkey41]: https://docs.openssl.org/4.1/man1/openssl-pkey/

mod asn1;

use baldssl_core::{
    Error, Result,
    der::syntax::{ObjectId, ObjectIdentifier, RawTlv, encode as encode_with},
    encoding::Encodable,
    pem::Pem,
};
use baldssl_crypto::{
    algebra::{
        curve::{Curve, ShortWeierstrass},
        field::PrimeField,
    },
    instances::{P256, P384, P521},
    keys::{EcKeyPair, EdDsaKeyPair},
    os_rng::{self, RngError},
    signature::eddsa::Ed25519Parameters,
};

use crate::asn1::{
    CURVE_PRIVATE_KEY, EC_PRIVATE_KEY, ID_EC_PUBLIC_KEY, ID_ED25519,
    PRIME256V1, PRIVATE_KEY_INFO, SECP384R1, SECP521R1,
};

/// A key type.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Algorithm {
    /// NIST P-256 (`prime256v1`).
    P256,
    /// NIST P-384 (`secp384r1`).
    P384,
    /// NIST P-521 (`secp521r1`).
    P521,
    /// Ed25519.
    Ed25519,
}

impl Algorithm {
    /// The length of the private key in bytes: the scalar at the full
    /// length of the group order (32, 48, 66), or the 32-byte Ed25519 seed.
    #[must_use]
    pub fn secret_len(self) -> usize {
        match self {
            Algorithm::P256 => <P256 as Curve>::Scalar::BYTES,
            Algorithm::P384 => <P384 as Curve>::Scalar::BYTES,
            Algorithm::P521 => <P521 as Curve>::Scalar::BYTES,
            Algorithm::Ed25519 => 32,
        }
    }
}

/// A private key: one typed key pair per algorithm, the sum of the key
/// types. Each operation is one `match` whose arms call generic code.
pub enum PrivateKey {
    /// A P-256 key pair.
    P256(EcKeyPair<P256>),
    /// A P-384 key pair.
    P384(EcKeyPair<P384>),
    /// A P-521 key pair.
    P521(EcKeyPair<P521>),
    /// An Ed25519 key pair.
    Ed25519(EdDsaKeyPair<Ed25519Parameters>),
}

/// The algorithm only: the key pairs never print their secret, and this
/// does not print the public key either.
impl core::fmt::Debug for PrivateKey {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.debug_struct("PrivateKey")
            .field("algorithm", &self.algorithm())
            .finish_non_exhaustive()
    }
}

fn rng_error(e: RngError) -> Error {
    match e {
        RngError::Unsupported => {
            Error::unsupported("key generation: no source of randomness")
        }
        RngError::Os(_) => Error::Io {
            context: "reading randomness".into(),
            message: e.to_string(),
        },
    }
}

/// The EC key pair of a secret scalar given big-endian at full length.
fn ec_pair<C>(secret: &[u8]) -> Result<EcKeyPair<C>>
where
    C: ShortWeierstrass,
{
    let (d, valid) = C::Scalar::from_bytes_be(secret);
    if !valid.to_bool_vartime() {
        return Err(Error::invalid("private scalar not in [1, n - 1]"));
    }
    EcKeyPair::from_secret(d)
        .ok_or_else(|| Error::invalid("private scalar not in [1, n - 1]"))
}

/// The PKCS#8 encoding of an EC key pair on the curve named `curve`.
fn ec_pkcs8<C>(pair: &EcKeyPair<C>, curve: &ObjectId) -> Vec<u8>
where
    C: ShortWeierstrass,
{
    let ec_private_key = encode_with(
        &EC_PRIVATE_KEY,
        &(
            1,
            (
                pair.secret().to_bytes_be(),
                (None, (Some(pair.public().encode()), ())),
            ),
        ),
    );
    let parameters = RawTlv::encode(&ObjectIdentifier, curve);
    encode_with(
        &PRIVATE_KEY_INFO,
        &(
            0,
            (
                (ID_EC_PUBLIC_KEY, (Some(parameters), ())),
                (ec_private_key, ()),
            ),
        ),
    )
}

impl PrivateKey {
    /// A new random key: the secret drawn uniformly from the operating
    /// system's randomness.
    ///
    /// # Errors
    ///
    /// When the operating system provides no randomness.
    pub fn generate(algorithm: Algorithm) -> Result<Self> {
        Ok(match algorithm {
            Algorithm::P256 => PrivateKey::P256(
                EcKeyPair::generate(os_rng::fill).map_err(rng_error)?,
            ),
            Algorithm::P384 => PrivateKey::P384(
                EcKeyPair::generate(os_rng::fill).map_err(rng_error)?,
            ),
            Algorithm::P521 => PrivateKey::P521(
                EcKeyPair::generate(os_rng::fill).map_err(rng_error)?,
            ),
            Algorithm::Ed25519 => PrivateKey::Ed25519(
                EdDsaKeyPair::generate(os_rng::fill).map_err(rng_error)?,
            ),
        })
    }

    /// The key with this secret: the scalar $d$ big-endian at its full
    /// length, or the 32-byte Ed25519 seed.
    ///
    /// # Errors
    ///
    /// [`Error::Invalid`] for a wrong length or a scalar outside
    /// $[1, n - 1]$.
    pub fn from_secret(algorithm: Algorithm, secret: &[u8]) -> Result<Self> {
        if secret.len() != algorithm.secret_len() {
            return Err(Error::invalid("private key length"));
        }
        Ok(match algorithm {
            Algorithm::P256 => PrivateKey::P256(ec_pair(secret)?),
            Algorithm::P384 => PrivateKey::P384(ec_pair(secret)?),
            Algorithm::P521 => PrivateKey::P521(ec_pair(secret)?),
            Algorithm::Ed25519 => {
                let seed: [u8; 32] =
                    secret.try_into().map_err(|_| Error::invalid("seed"))?;
                PrivateKey::Ed25519(EdDsaKeyPair::from_seed(seed))
            }
        })
    }

    /// The key type.
    #[must_use]
    pub fn algorithm(&self) -> Algorithm {
        match self {
            PrivateKey::P256(_) => Algorithm::P256,
            PrivateKey::P384(_) => Algorithm::P384,
            PrivateKey::P521(_) => Algorithm::P521,
            PrivateKey::Ed25519(_) => Algorithm::Ed25519,
        }
    }

    /// The public key: an uncompressed point (`04 || x || y`, big-endian),
    /// or the 32-byte Ed25519 encoding (little-endian, RFC 8032).
    #[must_use]
    pub fn public_key(&self) -> Vec<u8> {
        match self {
            PrivateKey::P256(k) => k.public().encode(),
            PrivateKey::P384(k) => k.public().encode(),
            PrivateKey::P521(k) => k.public().encode(),
            PrivateKey::Ed25519(k) => k.public().to_vec(),
        }
    }

    /// The secret as [`PrivateKey::from_secret`] takes it.
    #[cfg(test)]
    pub(crate) fn secret_bytes(&self) -> Vec<u8> {
        match self {
            PrivateKey::P256(k) => k.secret().to_bytes_be(),
            PrivateKey::P384(k) => k.secret().to_bytes_be(),
            PrivateKey::P521(k) => k.secret().to_bytes_be(),
            PrivateKey::Ed25519(k) => k.seed().to_vec(),
        }
    }
}

/// The PKCS#8 `PrivateKeyInfo`, DER, as `openssl genpkey` writes it (see
/// the crate documentation).
impl Encodable for PrivateKey {
    type Bytes = Vec<u8>;

    fn encode(&self) -> Vec<u8> {
        match self {
            PrivateKey::P256(k) => ec_pkcs8(k, &PRIME256V1),
            PrivateKey::P384(k) => ec_pkcs8(k, &SECP384R1),
            PrivateKey::P521(k) => ec_pkcs8(k, &SECP521R1),
            PrivateKey::Ed25519(k) => {
                let curve_private_key =
                    encode_with(&CURVE_PRIVATE_KEY, &k.seed().to_vec());
                encode_with(
                    &PRIVATE_KEY_INFO,
                    &(0, ((ID_ED25519, (None, ())), (curve_private_key, ()))),
                )
            }
        }
    }
}

/// PKCS#8 in PEM: `-----BEGIN PRIVATE KEY-----` ([RFC 7468, section
/// 10][rfc7468]).
///
/// [rfc7468]: https://www.rfc-editor.org/rfc/rfc7468#section-10
impl Pem for PrivateKey {
    const LABEL: &'static str = "PRIVATE KEY";
}

