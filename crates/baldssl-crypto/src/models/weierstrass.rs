//! The models of a short Weierstrass curve with $a = -3$, generic over the
//! curve ([`crate::algebra::curve::ShortWeierstrass`]); the NIST curves
//! P-256, P-384 and P-521 are instances ([`crate::instances`]).
//!
//! # The curves
//!
//! Each is the short Weierstrass curve $y^2 = x^3 - 3x + b$ over a prime
//! field $\mathbb{F}_p$, with a generator $G$ of prime order $n$. A point is a
//! zero of $f(x, y) = y^2 - x^3 + 3x - b$ with coordinates in
//! $\mathbb{F}_p$, together with one point at infinity $O$, the identity,
//! which no zero of $f$ represents.
//!
//! # Models
//!
//! Points are represented in three models of the same curve. The affine
//! chart misses $O$; the two others complete it in a projective space, where
//! a point is a class of nonzero triples under a scaling with weights
//! $(w_X, w_Y, w_Z)$: $(X : Y : Z) = (\lambda^{w_X} X : \lambda^{w_Y} Y :
//! \lambda^{w_Z} Z)$ for every nonzero $\lambda$. The equation must be
//! homogeneous for the weights so that its zeros are classes, and the
//! affine coordinates are the quotients of weight zero.
//!
//! | Model      | Type                         | Weights     | Equation                          | Affine point         | Identity                         |
//! | ---------- | ---------------------------- | ----------- | --------------------------------- | -------------------- | -------------------------------- |
//! | Affine     | [`affine::Affine`]           | none        | $y^2 = x^3 - 3x + b$              | $(x, y)$             | a flag; stored as $(0, 0)$       |
//! | Projective | [`projective::Projective`]   | $(1, 1, 1)$ | $Y^2 Z = X^3 - 3 X Z^2 + b Z^3$   | $(X / Z, Y / Z)$     | $(0 : 1 : 0)$                    |
//! | Jacobian   | [`jacobian::Jacobian`]       | $(2, 3, 1)$ | $Y^2 = X^3 - 3 X Z^4 + b Z^6$     | $(X / Z^2, Y / Z^3)$ | any $Z = 0$, stored as $(0, 0, 0)$ |
//!
//! The affine model is for encoding and decoding. The projective model has
//! complete formulas, which the constant-time scalar multiplication
//! ([`crate::algebra::group::scalar_mul`]) uses for secrets. The Jacobian model has faster but incomplete
//! formulas, variable time, for public points.
//!
//! # Why the weights are $(2, 3, 1)$
//!
//! Let $L(nO)$ be the functions on the curve whose only pole is at $O$, of
//! order at most $n$. By the Riemann-Roch theorem it has dimension $n$ for
//! $n \geq 1$, with $L(2O) = \langle 1, x \rangle$ and
//! $L(3O) = \langle 1, x, y \rangle$: $x$ has a pole of order 2 at $O$ and $y$
//! one of order 3 (Silverman, [*The Arithmetic of Elliptic Curves*][silverman], III.3).
//! The graded ring $\bigoplus_n L(nO)$ is generated by $Z$ (the constant 1,
//! in degree 1), $X$ (degree 2) and $Y$ (degree 3), with one relation in
//! degree 6, the Jacobian equation: the weights are the pole orders. Keeping
//! only the degrees divisible by 3 gives a ring generated by
//! $L(3O) = \langle 1, x, y \rangle$ in degree 1, whose equation is the cubic
//! of the projective plane. Both rings describe the same curve.
//!
//! # Maps between the models
//!
//! In [`maps`], as `From` impls, each stated next to its code.
//!
//! [silverman]: https://doi.org/10.1007/978-0-387-09494-6

